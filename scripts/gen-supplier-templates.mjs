const csvCell = (v) => {
  const s = v == null ? "" : String(v);
  return /[;"\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};
// BOM + «;» — так файл корректно открывается в Excel с русской локалью.
