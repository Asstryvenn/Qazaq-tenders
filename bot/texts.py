def reason_text(code: str, data: Dict[str, Any], lang: Lang) -> str:
    """Структурированная причина движка → фраза на языке пользователя."""
    kz = lang == "kz"
    if code == "gap":
        d, deficit, pay = data["day"], money(data["deficit"], lang), data["payDay"]
        return (
            f"кассалық алшақтық {d}-күннен, тереңдігі −{deficit}; төлем {pay}-күні"
            if kz
            else f"кассовый разрыв с {d}-го дня, глубина −{deficit}; оплата на {pay}-й день"
        )
    if code == "lowMargin":
        return f"маржа өте төмен: {pct(data['margin'])}" if kz else f"маржа слишком низкая: {pct(data['margin'])}"
    if code == "thinMargin":
        return f"маржа жұқа: {pct(data['margin'])}" if kz else f"тонкая маржа: {pct(data['margin'])}"
    if code == "overRadius":
        return (
            f"қашықтық {num(data['dist'])} км — радиустан ({num(data['max'])} км) асады"
            if kz
            else f"{num(data['dist'])} км — дальше радиуса логистики ({num(data['max'])} км)"
        )
    if code == "bankHeavy":
        return (
            f"кредит пайызы пайданың {pct(data['pct'], 0)} жейді ({money(data['bank'], lang)})"
            if kz
            else f"проценты по кредиту съедают {pct(data['pct'], 0)} прибыли ({money(data['bank'], lang)})"
        )
    if code == "penalty":
        return (
            f"айыппұл {pct(data['ratePct'], 2)}/күн: {data['slip']} күн кешіксе — шарттың {pct(data['pct'])}"
            if kz
            else f"неустойка {pct(data['ratePct'], 2)}/день: просрочка {data['slip']} дн. = {pct(data['pct'])} договора"
        )
    if code == "experience":
        return (
            f"тәжірибе {num(data['have'])} жыл, талап — {num(data['need'])} жыл"
            if kz
            else f"опыт {num(data['have'])} лет, требуется {num(data['need'])}"
        )
    if code == "certs":
        missing = ", ".join(esc(c) for c in data["missing"])
        return f"сертификат жоқ: {missing}" if kz else f"нет сертификатов: {missing}"
    if code == "hidden":
        return f"{esc(data['reason'])} ({'бет' if kz else 'стр.'} {data['page']})"
    if code == "lateScenario":
        cap = (" (10% шегі)" if kz else " (потолок 10%)") if data["capped"] else ""
        return (
            f"{data['days']} күн кешігу → айыппұл {money(data['penalty'], lang)}{cap}"
            if kz
            else f"просрочка {data['days']} дн. → неустойка {money(data['penalty'], lang)}{cap}"
        )
    if code == "safe":
        return (
            f"баланс нөлден төмен түспейді (ең төмені {money(data['min'], lang)})"
            if kz
            else f"баланс не уходит в минус (минимум {money(data['min'], lang)})"
        )
    return code


