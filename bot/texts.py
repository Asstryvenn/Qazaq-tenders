def _dec(value: float, digits: int) -> str:
    s = f"{value:,.{digits}f}".replace(",", " ").replace(".", ",")
    return s[:-2] if digits == 1 and s.endswith(",0") else s


def money(value: float, lang: Lang, signed: bool = False) -> str:
    """84000000 → «84 млн ₸», 520000 → «520 тыс. ₸» / «520 мың ₸»."""
    sign = "−" if value < 0 else ("+" if signed and value > 0 else "")
    a = abs(value)
    if a >= 1e9:
        s = f"{_dec(a / 1e9, 1)} млрд"
    elif a >= 1e6:
        s = f"{_dec(a / 1e6, 1)} млн"
    elif a >= 1e3:
        s = f"{_dec(a / 1e3, 0)} {'мың' if lang == 'kz' else 'тыс.'}"
    else:
        s = _dec(a, 0)
    return f"{sign}{s} ₸"


def pct(value: float, digits: int = 1, signed: bool = False) -> str:
    sign = "+" if signed and value > 0 else ""
    return f"{sign}{value:.{digits}f}".replace(".", ",").replace("-", "−") + "%"


def num(value: float, digits: int = 0) -> str:
    return _dec(value, digits)


